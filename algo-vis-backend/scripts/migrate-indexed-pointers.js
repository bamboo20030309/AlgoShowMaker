#!/usr/bin/env node
// Explicit, one-time authoring migration. This is not a parser compatibility
// layer: newly authored brackets always select data, never create pointers.
const fs = require('node:fs');
const path = require('node:path');

function splitTop(text, separator) {
  const result = []; let start = 0, depth = 0, quote = '', escaped = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quote) { if (escaped) escaped = false; else if (c === '\\') escaped = true; else if (c === quote) quote = ''; continue; }
    if (c === '"' || c === "'") { quote = c; continue; }
    if ('[({'.includes(c)) depth++;
    if ('])}'.includes(c)) depth--;
    if (depth === 0 && separator(c, i)) { result.push(text.slice(start, i)); start = i + 1; }
  }
  result.push(text.slice(start)); return result;
}

function migrateSource(source) {
  const newline = source.includes('\r\n') ? '\r\n' : '\n';
  const lines = source.split(/\r?\n/); const output = []; let pending = [];
  const flush = () => { output.push(...pending); pending = []; };
  for (const line of lines) {
    const match = line.match(/^(\s*)\/\/\s*(?:[\w.-]+\s*:\s*)?@(frame|object)\b\s*(.*)$/);
    if (!match) { flush(); output.push(line); continue; }
    if (match[2] === 'frame') flush();
    const payload = match[3];
    // Locate modifiers only outside nested index/constructor expressions.
    let boundary = payload.length;
    splitTop(payload, (c, i) => {
      if (/\s/.test(c) && /^\s+(?:render|with|as|in|at|offset|when)\b/.test(payload.slice(i))) boundary = Math.min(boundary, i);
      return false;
    });
    const head = payload.slice(0, boundary);
    const suffix = payload.slice(boundary);
    const pointers = [];
    const targets = splitTop(head, c => c === ',').map(target => {
      const m = target.trim().match(/^((?:char\(\s*)?([A-Za-z_]\w*)(?:\s*\))?)(.*)$/);
      if (!m || !m[3].trim().startsWith('[')) return target;
      const groups = []; let cursor = 0; const tail = m[3].trim();
      while (cursor < tail.length && tail[cursor] === '[') {
        const start = ++cursor; let depth = 1;
        while (cursor < tail.length && depth) { if (tail[cursor] === '[') depth++; else if (tail[cursor] === ']') depth--; cursor++; }
        if (depth) return target;
        groups.push(tail.slice(start, cursor - 1));
        while (/\s/.test(tail[cursor] || '')) cursor++;
      }
      if (cursor !== tail.length || !groups.length) return target;
      groups.forEach((group, dimension) => {
        splitTop(group, c => c === ',').forEach(expression => {
          const axis = groups.length > 1 ? (dimension === 0 ? '.row' : '.column') : '';
          pointers.push(`${match[1]}// @pointer ${expression.trim()} at ${m[2]}${axis}`);
        });
      });
      return m[1];
    });
    output.push(pointers.length ? line.slice(0, line.length - payload.length) + targets.join(',') + suffix : line);
    pending.push(...pointers);
  }
  flush(); return output.join(newline);
}

// Preserve JSON field order and all non-code data. Never rewrite Trace events
// or old frame metadata as though they had been generated by a new compiler.
function migrateJSON(value) {
  if (typeof value === 'string') return migrateSource(value);
  if (Array.isArray(value)) return value.map(migrateJSON);
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, migrateJSON(item)]));
  return value;
}

function migrateJavaScript(source) {
  // Acorn is used only by this maintenance command, not by the application.
  const acorn = require('acorn'); const edits = [];
  for (const token of acorn.tokenizer(source, { ecmaVersion: 'latest', allowHashBang: true })) {
    if (!['string', 'template'].includes(token.type.label) || typeof token.value !== 'string') continue;
    const value = migrateSource(token.value);
    if (value === token.value) continue;
    edits.push({ from: token.start, to: token.end, text: token.type.label === 'string'
      ? JSON.stringify(value) : value.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') });
  }
  for (const edit of edits.reverse()) source = source.slice(0, edit.from) + edit.text + source.slice(edit.to);
  return source;
}

if (require.main === module) {
  const files = process.argv.slice(2); const write = files.includes('--write');
  for (const file of files.filter(file => file !== '--write')) {
    const source = fs.readFileSync(file, 'utf8');
    const next = file.endsWith('.js') ? migrateJavaScript(source) : file.endsWith('.json')
      ? JSON.stringify(migrateJSON(JSON.parse(source)), null, 2) + '\n' : migrateSource(source);
    if (source !== next) { console.log(path.relative(process.cwd(), file)); if (write) fs.writeFileSync(file, next); }
  }
}
module.exports = { migrateSource, migrateJSON, migrateJavaScript };
